"""
trajectory_simulation_v2.py — Review 1 remark: "Work on your dataset: make
sure the range for different parameters are sensible, make your synthetic
dataset sensible/reliable enough"
MaternaCare AI

Regenerates Phase 4's synthetic 4-visit longitudinal trajectory dataset
with two concrete fixes to reliability, both aimed squarely at this remark:

1. GROUNDED ANCHORS, NOT ARBITRARY RANGES: each synthetic patient's Visit-1
   vitals are bootstrap-sampled from the real 1,014-record dataset (with
   the 10 implausible rows found by data_validation.py excluded first, so
   the sensor/entry errors aren't propagated into the synthetic data).
   This guarantees the synthetic Visit-1 distribution matches the real
   distribution by construction, rather than trusting hand-picked min/max
   sliders to happen to look right.

2. BOUNDED, VALIDATED DRIFT: Visits 2-4 are generated by applying a
   clinically-plausible per-visit change (a small random walk with an
   optional trend direction for "risk-informed" trajectories, matching
   Phase 4's original intent), but every generated value is clipped to
   data_validation.py's PLAUSIBLE_RANGE after each step — the same range
   definitions used to validate the real dataset and used by the Phase 8
   voice parser, so there is one shared, clinically-cited source of truth
   for "sensible" across the whole project rather than three different
   implicit definitions in three different files.

   Per-visit deltas are sized as a fraction of each vital's own observed
   real-world standard deviation (from the real dataset), not an arbitrary
   fixed number — a BP is allowed to move further between visits than a
   temperature would, because that's what the real data's own variability
   implies is plausible.

After generation, `validate_synthetic_dataset()` runs three checks and
reports pass/fail rather than assuming the generator worked:
  a) every generated value falls inside PLAUSIBLE_RANGE (by construction,
     but checked anyway rather than trusted)
  b) the synthetic Visit-1 distribution is statistically indistinguishable
     from the real distribution (Kolmogorov-Smirnov test per vital)
  c) trajectories move gradually (no implausible visit-to-visit jumps
     larger than a clinically-set ceiling)
"""

import os
import sys
from pathlib import Path
import numpy as np
import pandas as pd
from scipy import stats

sys.path.insert(0, os.path.join(os.path.dirname(__file__)))
from data_validation import VITAL_RANGES, validate_dataframe, clip_to_plausible  # noqa: E402

FEATURES = ["Age", "SystolicBP", "DiastolicBP", "BS", "BodyTemp", "HeartRate"]

# Max plausible single-visit-to-visit change, as a fraction of each vital's
# real-world standard deviation (computed from the real dataset at runtime,
# see `_real_std` below) — e.g. a BP with real-world std of ~18mmHg can
# plausibly move a good deal between two prenatal visits weeks apart;
# BodyTemp (std ~1.4F) should barely move visit to visit outside of acute
# illness, which is exactly why its allowed drift fraction is smallest.
DRIFT_FRACTION_OF_STD = {
    "Age": 0.0,          # doesn't change meaningfully across a handful of visits
    "SystolicBP": 0.35,
    "DiastolicBP": 0.35,
    "BS": 0.30,
    "BodyTemp": 0.15,    # small — a big jump here means fever, a discrete event, not drift
    "HeartRate": 0.30,
}


def _load_clean_real_data(csv_path: str) -> pd.DataFrame:
    """Real dataset with the implausible rows (found by data_validation.py)
    excluded, so synthetic generation bootstraps only from trustworthy
    anchors."""
    df = pd.read_csv(csv_path)
    df["RiskLevel"] = df["RiskLevel"].str.strip().str.lower()
    validated = validate_dataframe(df)
    clean = df.loc[~validated["any_implausible"]].reset_index(drop=True)
    return clean


def _real_std(clean_df: pd.DataFrame) -> dict:
    return {col: float(clean_df[col].std()) for col in FEATURES}


def generate_trajectories(csv_path: str, n_patients: int = 300, n_visits: int = 4,
                           risk_informed_fraction: float = 0.4, seed: int = 42) -> pd.DataFrame:
    """
    Generate a synthetic longitudinal dataset.

    Parameters
    ----------
    n_patients : number of synthetic patients
    n_visits : visits per patient (Phase 4's original design used 4)
    risk_informed_fraction : fraction of patients assigned a deliberate
        worsening or improving trend (vs. random walk with no trend),
        matching Phase 4's "risk-informed" framing — used later to test
        whether a downstream classifier can recover the trend direction
        from the trajectory shape.
    seed : for reproducibility

    Returns
    -------
    DataFrame with columns: patient_id, visit_number, trend_label, + FEATURES
    """
    rng = np.random.default_rng(seed)
    clean = _load_clean_real_data(csv_path)
    real_std = _real_std(clean)

    rows = []
    anchor_sample = clean.sample(n=n_patients, replace=True, random_state=seed).reset_index(drop=True)

    for pid in range(n_patients):
        anchor = anchor_sample.iloc[pid]
        is_risk_informed = rng.random() < risk_informed_fraction
        if is_risk_informed:
            trend_sign = rng.choice([-1, 1])  # -1 = improving, +1 = worsening
            trend_label = "worsening" if trend_sign == 1 else "improving"
        else:
            trend_sign = 0
            trend_label = "stable"

        current = {col: float(anchor[col]) for col in FEATURES}
        for visit in range(1, n_visits + 1):
            if visit > 1:
                for col in FEATURES:
                    max_step = DRIFT_FRACTION_OF_STD[col] * real_std[col]
                    if max_step == 0:
                        continue
                    # trend nudges the mean of the random step; noise still
                    # allows some visits to buck the overall trend, which is
                    # realistic (not every visit moves the same direction)
                    trend_component = trend_sign * 0.4 * max_step
                    noise_component = rng.normal(loc=0, scale=max_step * 0.5)
                    step = trend_component + noise_component
                    current[col] = clip_to_plausible(current[col] + step, col)

            row = {"patient_id": pid, "visit_number": visit, "trend_label": trend_label}
            row.update(current)
            rows.append(row)

    return pd.DataFrame(rows)


# ---------------------------------------------------------------------------
# Validation of the synthetic output
# ---------------------------------------------------------------------------

def validate_synthetic_dataset(synth_df: pd.DataFrame, real_csv_path: str,
                                max_visit_jump_fraction: float = 1.0) -> dict:
    """
    Runs the three checks described in the module docstring. Returns a dict
    report rather than just printing, so this can be called from tests.
    """
    report = {}

    # (a) plausibility of every generated value
    validated = validate_dataframe(synth_df, columns=FEATURES)
    n_bad = int(validated["any_implausible"].sum())
    report["plausibility_check"] = {
        "n_rows": len(synth_df),
        "n_implausible_rows": n_bad,
        "pass": n_bad == 0,
    }

    # (b) Visit-1 distribution vs real distribution, per vital, via KS test.
    # Null hypothesis: same distribution. We WANT to fail to reject (p > 0.05)
    # for each vital, i.e. we want the synthetic Visit-1 data to look
    # statistically like the real data it was bootstrapped from.
    clean_real = _load_clean_real_data(real_csv_path)
    visit1 = synth_df[synth_df["visit_number"] == 1]
    ks_results = {}
    for col in FEATURES:
        stat, p = stats.ks_2samp(clean_real[col], visit1[col])
        ks_results[col] = {"ks_statistic": float(stat), "p_value": float(p), "distributions_match": bool(p > 0.05)}
    report["visit1_distribution_check"] = ks_results
    report["visit1_distribution_check_all_pass"] = all(v["distributions_match"] for v in ks_results.values())

    # (c) visit-to-visit jump sanity: no single step should exceed a
    # clinically implausible fraction of the vital's full plausible range
    jump_violations = 0
    for pid, group in synth_df.sort_values(["patient_id", "visit_number"]).groupby("patient_id"):
        for col in FEATURES:
            diffs = group[col].diff().dropna().abs()
            r = VITAL_RANGES[col]
            full_range = r.plausible_hi - r.plausible_lo
            ceiling = max_visit_jump_fraction * 0.5 * full_range  # generous but finite ceiling
            jump_violations += int((diffs > ceiling).sum())
    report["visit_to_visit_jump_check"] = {
        "n_violations": jump_violations,
        "pass": jump_violations == 0,
    }

    report["overall_pass"] = (
        report["plausibility_check"]["pass"]
        and report["visit1_distribution_check_all_pass"]
        and report["visit_to_visit_jump_check"]["pass"]
    )
    return report


def format_validation_report(report: dict) -> str:
    lines = ["=" * 72, "SYNTHETIC TRAJECTORY DATASET — VALIDATION REPORT", "=" * 72]

    p = report["plausibility_check"]
    lines.append(f"\n(a) Plausibility: {p['n_implausible_rows']}/{p['n_rows']} rows implausible "
                 f"-> {'PASS' if p['pass'] else 'FAIL'}")

    lines.append("\n(b) Visit-1 distribution vs real data (Kolmogorov-Smirnov test, want p > 0.05):")
    for col, r in report["visit1_distribution_check"].items():
        status = "PASS" if r["distributions_match"] else "FAIL"
        lines.append(f"    {col:12s} KS={r['ks_statistic']:.4f}  p={r['p_value']:.4f}  -> {status}")
    overall_b = "PASS" if report["visit1_distribution_check_all_pass"] else "FAIL"
    lines.append(f"    Overall: {overall_b}")

    j = report["visit_to_visit_jump_check"]
    lines.append(f"\n(c) Visit-to-visit jump sanity: {j['n_violations']} violations -> "
                 f"{'PASS' if j['pass'] else 'FAIL'}")

    lines.append(f"\nOVERALL: {'PASS — synthetic dataset is sensible and reliable by these checks' if report['overall_pass'] else 'FAIL — see above'}")
    return "\n".join(lines)


