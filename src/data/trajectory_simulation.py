"""
Phase 4 — Longitudinal Trajectory Simulation
================================================
The public Maternal Health Risk dataset only has ONE recorded visit per
patient. To test whether tracking a patient's vitals ACROSS visits helps
predict risk better than a single snapshot, this script simulates a
plausible visit history for each real patient, ending at their actual
recorded (ground-truth) vitals and risk label.

Simulation design:
  - Each real record becomes the FINAL (most recent) visit for a simulated
    patient — its vitals and risk label are the real, unmodified ground truth.
  - Each patient is assigned one of four trajectory PATTERNS, chosen
      PROBABILISTICALLY based on their actual risk level (not purely at
      random — see build_longitudinal_dataset() for details). Patients
      trending toward worse outcomes are more likely to show "Sudden
      Deterioration" or "Gradually Worsening" patterns; patients with
      better outcomes are more likely "Stable" or "Improving". This mirrors
      the same fix applied to the Phase 2 trimester simulation: a
      risk-informed simulation gives the resulting trend features a real,
      learnable signal, rather than being pure noise uncorrelated with the
      prediction target.
      Pattern types:
      "Stable"               - vitals stay close to the final value throughout
      "Gradually Worsening"  - vitals rise smoothly toward the final value
                                 (final visit is the worst point)
      "Sudden Deterioration" - vitals stay near a milder baseline, then jump
                                 sharply in the last visit or two
      "Improving"            - vitals start elevated and decline toward the
                                 final value (final visit is the best point)
  - Earlier (synthetic) visits are generated by applying that pattern's
    shape to each feature, scaled by the feature's real standard deviation,
    plus random noise — grounded in the actual data's variability, not
    arbitrary numbers.

IMPORTANT — This is a documented simulation, not real longitudinal data.
State this explicitly in your report (as already noted in the project
write-up): no public dataset with real multi-visit maternal health records
was available, so trajectories are simulated to demonstrate the
trend-aware modeling approach.

What this script produces:
  1. The full simulated longitudinal dataset (long format: one row per
     patient per visit).
  2. Example trajectory plots (one per pattern) for your report/slides.
  3. Engineered trend features (rate of change, slope, rolling average,
     volatility) per patient.
  4. A trajectory-PATTERN classifier (sanity check: can the trend features
     actually recover the pattern we simulated?).
  5. A risk-level classifier trained on latest vitals + trend features,
     compared against the Phase 2 baseline (latest vitals only) to test
     whether trend information adds real predictive value.

Usage:
    python src/data/trajectory_simulation.py
"""

import os
import sys
import json
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import joblib

from sklearn.model_selection import train_test_split, cross_val_score, RepeatedStratifiedKFold
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, f1_score, classification_report
from scipy import stats

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "models"))
from baseline import load_data, find_label_column, MATERNAL_CSV

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MODELS_DIR = os.path.join(PROJECT_ROOT, "models")
OUT_DIR = os.path.join(PROJECT_ROOT, "docs", "phase4_outputs")
os.makedirs(MODELS_DIR, exist_ok=True)
os.makedirs(OUT_DIR, exist_ok=True)

sns.set_style("whitegrid")
PINK_PALETTE = {"Stable": "#D9799E", "Gradually Worsening": "#9C3B63",
                 "Sudden Deterioration": "#4A2438", "Improving": "#F2AFC6"}

RANDOM_SEED = 42
N_VISITS = 4
FEATURES = ["SystolicBP", "DiastolicBP", "BS", "BodyTemp", "HeartRate"]
PATTERNS = ["Stable", "Gradually Worsening", "Sudden Deterioration", "Improving"]


def pattern_shape(pattern, t):
    """
    Returns a value in roughly [-1, 1] describing how far a feature should
    be from its final value at normalized time t (0 = first visit, 1 = final
    visit), for a given trajectory pattern. Multiplied by the feature's
    drift magnitude to get the actual offset.
    """
    if pattern == "Stable":
        return 0.0
    if pattern == "Gradually Worsening":
        return -(1 - t)  # starts below final, rises smoothly to final
    if pattern == "Sudden Deterioration":
        steepness = 12
        return -(1 - 1 / (1 + np.exp(-steepness * (t - 0.75))))  # flat, then sharp jump near the end
    if pattern == "Improving":
        return (1 - t)  # starts above final, declines to final
    raise ValueError(f"Unknown pattern: {pattern}")


def simulate_patient_visits(row, feature_stds, pattern, n_visits, rng):
    visits = []
    for i in range(n_visits):
        t = i / (n_visits - 1)
        visit = {"VisitNumber": i + 1}
        for feat in FEATURES:
            final_val = row[feat]
            if i == n_visits - 1:
                val = final_val  # final visit = real recorded ground truth, unmodified
            else:
                drift_mag = feature_stds[feat] * rng.uniform(0.5, 1.0)
                shape = pattern_shape(pattern, t)
                noise = rng.normal(0, feature_stds[feat] * 0.05)
                val = final_val + shape * drift_mag + noise
            visit[feat] = val
        visit["Age"] = row["Age"]
        visits.append(visit)
    return visits


def build_longitudinal_dataset(df, label_col):
    """
    Simulates visit history per patient, with each patient's trajectory
    PATTERN assigned probabilistically based on their actual risk level
    (not purely at random). This mirrors the same fix applied to the
    trimester simulation in Phase 2: a risk-informed simulation gives trend
    features a genuine, clinically plausible signal to learn from, instead
    of being pure noise uncorrelated with the outcome.

    Rationale: patients trending toward worse outcomes (High Risk) are
    clinically more likely to show "Sudden Deterioration" or "Gradually
    Worsening" patterns; patients with better outcomes (Low Risk) are more
    likely "Stable" or "Improving". This is a genuine tendency (probabilistic,
    not deterministic) — some randomness remains so it isn't a trivial giveaway.
    """
    rng = np.random.default_rng(RANDOM_SEED)
    feature_stds = {feat: df[feat].std() for feat in FEATURES}

    # Map risk labels to 0/1/2 the same way baseline.py does, to condition
    # pattern probabilities on risk level.
    risk_class = []
    for val in df[label_col]:
        v = str(val).strip().lower()
        if "low" in v:
            risk_class.append(0)
        elif "mid" in v:
            risk_class.append(1)
        elif "high" in v:
            risk_class.append(2)
        else:
            risk_class.append(1)  # fallback: treat unknown as mid
    risk_class = np.array(risk_class)

    # PATTERNS order: ["Stable", "Gradually Worsening", "Sudden Deterioration", "Improving"]
    pattern_probs_by_risk = {
        0: [0.40, 0.15, 0.10, 0.35],  # Low risk    -> mostly Stable/Improving
        1: [0.25, 0.30, 0.20, 0.25],  # Mid risk    -> fairly mixed
        2: [0.10, 0.35, 0.40, 0.15],  # High risk   -> mostly Worsening/Sudden Deterioration
    }

    patterns_assigned = np.array([
        rng.choice(PATTERNS, p=pattern_probs_by_risk[rc]) for rc in risk_class
    ])

    all_visits = []
    for patient_id, (idx, row) in enumerate(df.iterrows()):
        pattern = patterns_assigned[patient_id]
        visits = simulate_patient_visits(row, feature_stds, pattern, N_VISITS, rng)
        for v in visits:
            v["PatientID"] = patient_id
            v["Pattern"] = pattern
            v["RiskLevel"] = row[label_col]
        all_visits.extend(visits)

    long_df = pd.DataFrame(all_visits)
    print(f"Generated {long_df['PatientID'].nunique()} simulated patients x {N_VISITS} visits "
          f"= {len(long_df)} total visit records")
    print(f"\nPattern distribution:")
    print(long_df.drop_duplicates("PatientID")["Pattern"].value_counts())
    print(f"\nPattern distribution BY risk level (should show a real skew, not be uniform):")
    check_df = long_df.drop_duplicates("PatientID")[["Pattern", "RiskLevel"]]
    print(pd.crosstab(check_df["RiskLevel"], check_df["Pattern"], normalize="index").round(2))
    return long_df


def plot_example_trajectories(long_df):
    fig, axes = plt.subplots(2, 2, figsize=(12, 8))
    axes = axes.flatten()

    for i, pattern in enumerate(PATTERNS):
        patient_ids = long_df[long_df["Pattern"] == pattern]["PatientID"].unique()
        example_id = patient_ids[0]
        patient_data = long_df[long_df["PatientID"] == example_id].sort_values("VisitNumber")

        ax = axes[i]
        ax.plot(patient_data["VisitNumber"], patient_data["SystolicBP"],
                marker="o", label="Systolic BP", color=PINK_PALETTE[pattern], linewidth=2)
        ax2 = ax.twinx()
        ax2.plot(patient_data["VisitNumber"], patient_data["BS"],
                  marker="s", label="Blood Sugar", color="gray", linestyle="--", linewidth=1.5, alpha=0.7)

        ax.set_title(f"{pattern}\n(example patient, final risk: {patient_data['RiskLevel'].iloc[0]})")
        ax.set_xlabel("Visit Number")
        ax.set_ylabel("Systolic BP", color=PINK_PALETTE[pattern])
        ax2.set_ylabel("Blood Sugar", color="gray")
        ax.set_xticks(range(1, N_VISITS + 1))

    plt.tight_layout()
    out_path = os.path.join(OUT_DIR, "example_trajectories.png")
    plt.savefig(out_path, dpi=150)
    plt.close()
    print(f"\nSaved example trajectory plot: {out_path}")


def engineer_trend_features(long_df):
    records = []
    for patient_id, group in long_df.groupby("PatientID"):
        group = group.sort_values("VisitNumber")
        record = {"PatientID": patient_id, "Pattern": group["Pattern"].iloc[0],
                   "RiskLevel": group["RiskLevel"].iloc[0], "Age": group["Age"].iloc[0]}

        for feat in FEATURES:
            values = group[feat].values
            record[f"{feat}_latest"] = values[-1]
            record[f"{feat}_rate_of_change"] = (values[-1] - values[0]) / (len(values) - 1)
            record[f"{feat}_slope"] = np.polyfit(range(len(values)), values, 1)[0]
            record[f"{feat}_rolling_avg"] = values.mean()
            record[f"{feat}_volatility"] = values.std()

        records.append(record)

    return pd.DataFrame(records)


def evaluate_pattern_classifier(trend_df):
    print("\n" + "=" * 60)
    print("MODEL 1 — TRAJECTORY PATTERN CLASSIFIER (sanity check)")
    print("=" * 60)
    print("Can the engineered trend features recover the pattern we simulated?")

    feature_cols = [c for c in trend_df.columns if c not in ("PatientID", "Pattern", "RiskLevel")]
    X = trend_df[feature_cols]
    y = trend_df["Pattern"]

    X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2, random_state=RANDOM_SEED, stratify=y)

    clf = RandomForestClassifier(n_estimators=150, random_state=RANDOM_SEED)
    clf.fit(X_train, y_train)
    preds = clf.predict(X_test)
    acc = accuracy_score(y_test, preds)

    print(f"\nPattern classification accuracy: {acc:.4f}")
    print(classification_report(y_test, preds))
    if acc > 0.85:
        print("-> High accuracy confirms the trend features successfully capture the "
              "simulated trajectory shapes (the simulation + feature engineering are working correctly).")
    else:
        print("-> Lower than expected accuracy — trend features may need refinement to "
              "better distinguish between pattern shapes.")

    joblib.dump(clf, os.path.join(MODELS_DIR, "trajectory_pattern_classifier.joblib"))
    return {"accuracy": acc}


def evaluate_risk_classifier_with_trends(trend_df, X_orig, y_orig):
    print("\n" + "=" * 60)
    print("MODEL 2 — RISK CLASSIFIER: LATEST VITALS + TREND FEATURES vs. BASELINE")
    print("=" * 60)

    trend_df = trend_df.sort_values("PatientID").reset_index(drop=True)

    # Encode risk labels the same way baseline.py does
    y_risk = trend_df["RiskLevel"]
    order_map = {}
    for val in y_risk.unique():
        v = str(val).strip().lower()
        if "low" in v:
            order_map[val] = 0
        elif "mid" in v:
            order_map[val] = 1
        elif "high" in v:
            order_map[val] = 2
    y_encoded = y_risk.map(order_map)

    # Reduced trend feature set: keep only the most informative, least redundant
    # stats (latest value, rate of change, slope). Dropping rolling_avg and
    # volatility, which are highly correlated with the others and mainly add
    # noise/dimensionality without much unique signal.
    reduced_stats = ["latest", "rate_of_change", "slope"]
    trend_feature_cols = [f"{feat}_{stat}" for feat in FEATURES for stat in reduced_stats] + ["Age"]
    latest_only_cols = [f"{feat}_latest" for feat in FEATURES] + ["Age"]

    X_trend = trend_df[trend_feature_cols]
    X_latest = trend_df[latest_only_cols]

    print(f"Using a reduced trend feature set: {len(trend_feature_cols)} features "
          f"(down from {len(FEATURES) * 5 + 1} — dropped rolling_avg and volatility to reduce noise/dimensionality)")

    # ---- Single 80/20 split (kept for continuity with earlier phases) ----
    X_train_trend, X_test_trend, y_train, y_test = train_test_split(
        X_trend, y_encoded, test_size=0.2, random_state=RANDOM_SEED, stratify=y_encoded
    )
    trend_clf = RandomForestClassifier(n_estimators=150, random_state=RANDOM_SEED)
    trend_clf.fit(X_train_trend, y_train)
    trend_preds = trend_clf.predict(X_test_trend)
    trend_acc = accuracy_score(y_test, trend_preds)
    trend_f1 = f1_score(y_test, trend_preds, average="weighted")

    X_train_latest, X_test_latest, _, _ = train_test_split(
        X_latest, y_encoded, test_size=0.2, random_state=RANDOM_SEED, stratify=y_encoded
    )
    latest_clf = RandomForestClassifier(n_estimators=150, random_state=RANDOM_SEED)
    latest_clf.fit(X_train_latest, y_train)
    latest_preds = latest_clf.predict(X_test_latest)
    latest_acc = accuracy_score(y_test, latest_preds)
    latest_f1 = f1_score(y_test, latest_preds, average="weighted")

    print(f"\n--- Single 80/20 split (reduced feature set) ---")
    print(f"With latest vitals + reduced trend features: Accuracy={trend_acc:.4f}  Weighted F1={trend_f1:.4f}")
    print(f"With latest vitals ONLY:                      Accuracy={latest_acc:.4f}  Weighted F1={latest_f1:.4f}")
    print(f"Difference: {trend_acc - latest_acc:+.4f}")
    print("[NOTE: a single ~200-sample test split can be noisy — see the cross-validated "
          "comparison below for a more reliable verdict, as we learned in Phase 3.]")

    # ---- Cross-validated comparison (the more trustworthy number) ----
    print(f"\n--- Cross-validated comparison (5-fold x 5-repeat = 25 folds, paired) ---")
    cv = RepeatedStratifiedKFold(n_splits=5, n_repeats=5, random_state=RANDOM_SEED)

    trend_cv_scores = cross_val_score(
        RandomForestClassifier(n_estimators=150, random_state=RANDOM_SEED),
        X_trend, y_encoded, cv=cv, scoring="accuracy", n_jobs=-1
    )
    latest_cv_scores = cross_val_score(
        RandomForestClassifier(n_estimators=150, random_state=RANDOM_SEED),
        X_latest, y_encoded, cv=cv, scoring="accuracy", n_jobs=-1
    )

    print(f"With latest vitals + reduced trend features: {trend_cv_scores.mean():.4f} +/- {trend_cv_scores.std():.4f}")
    print(f"With latest vitals ONLY:                      {latest_cv_scores.mean():.4f} +/- {latest_cv_scores.std():.4f}")
    cv_improvement = trend_cv_scores.mean() - latest_cv_scores.mean()
    print(f"Mean difference: {cv_improvement:+.4f}")

    t_stat, p_value = stats.ttest_rel(trend_cv_scores, latest_cv_scores)
    print(f"Paired t-test: t={t_stat:.3f}, p={p_value:.4f}", end="  ")
    significant = p_value < 0.05
    if significant:
        direction = "helps" if cv_improvement > 0 else "hurts"
        print(f"-> Statistically significant: trend features {direction} (p < 0.05)")
    else:
        print("-> Not statistically significant — cannot conclude trend features meaningfully "
              "change performance either way on this simulated data.")

    if not significant:
        print("\n-> Combined with Phase 3's ceiling diagnostic, this is a coherent, defensible result: "
              "with a data-driven accuracy ceiling already limiting single-visit prediction, additional "
              "engineered features (real or simulated) have limited room to move the needle further.")

    joblib.dump(trend_clf, os.path.join(MODELS_DIR, "risk_classifier_with_trends.joblib"))

    return {
        "single_split": {
            "with_trend_features": {"accuracy": trend_acc, "f1_weighted": trend_f1},
            "latest_vitals_only": {"accuracy": latest_acc, "f1_weighted": latest_f1},
            "improvement": trend_acc - latest_acc,
        },
        "cross_validated": {
            "trend_cv_mean": float(trend_cv_scores.mean()), "trend_cv_std": float(trend_cv_scores.std()),
            "latest_cv_mean": float(latest_cv_scores.mean()), "latest_cv_std": float(latest_cv_scores.std()),
            "mean_improvement": float(cv_improvement),
            "t_statistic": float(t_stat), "p_value": float(p_value), "significant": bool(significant),
        },
    }


def main():
    print("=" * 60)
    print("PHASE 4 — LONGITUDINAL TRAJECTORY SIMULATION")
    print("=" * 60)

    if not os.path.exists(MATERNAL_CSV):
        raise FileNotFoundError(f"Dataset not found at {MATERNAL_CSV}. Complete Phase 1 first.")

    df = pd.read_csv(MATERNAL_CSV)
    label_col = find_label_column(df)

    long_df = build_longitudinal_dataset(df, label_col)
    plot_example_trajectories(long_df)

    trend_df = engineer_trend_features(long_df)
    print(f"\nEngineered {len([c for c in trend_df.columns if c not in ('PatientID','Pattern','RiskLevel')])} "
          f"trend features per patient (rate of change, slope, rolling average, volatility x {len(FEATURES)} vitals)")

    pattern_results = evaluate_pattern_classifier(trend_df)

    X_orig, y_orig, _, _ = load_data()
    risk_results = evaluate_risk_classifier_with_trends(trend_df, X_orig, y_orig)

    results = {"pattern_classifier": pattern_results, "risk_classifier_comparison": risk_results}
    summary_path = os.path.join(OUT_DIR, "phase4_trajectory_results.json")
    with open(summary_path, "w") as f:
        json.dump(results, f, indent=2, default=str)

    long_df.to_csv(os.path.join(PROJECT_ROOT, "data", "processed", "simulated_longitudinal_data.csv"), index=False)
    trend_df.to_csv(os.path.join(PROJECT_ROOT, "data", "processed", "trend_features.csv"), index=False)

    print(f"\nFull results saved to: {summary_path}")
    print(f"Simulated longitudinal data saved to: data/processed/simulated_longitudinal_data.csv")
    print(f"Trend features saved to: data/processed/trend_features.csv")
    print(f"Plots saved to: {OUT_DIR}/")
    print("\nNext step: Phase 5 — Hybrid Clustering for Iron-Deficiency (src/clustering/ga_kmeans.py)")


if __name__ == "__main__":
    main()